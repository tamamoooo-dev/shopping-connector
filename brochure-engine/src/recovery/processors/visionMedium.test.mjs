import assert from 'node:assert/strict';
import processor from './visionMedium.js';
import { recoveryRegistry } from './index.js';
let calls = 0;
const item = { offer:{image_url:'https://example.test/crop.jpg'}, attemptsBySource:{vision:{model:'ministral-14b-2512'}} };
assert.equal(processor.supports(item), false);
const outcome = await processor.run(item, { fetchImpl:async () => { calls++; throw Error('must not call'); } });
assert.equal(outcome.declined, true);
assert.equal(calls, 0);
assert.equal(processor.costHint.requests, 0);
assert.ok(recoveryRegistry);
console.log('Legacy recovery remains addressable and spends zero image/API requests.');
